// Bundles the game engine (room, hub, Jeopardy, Family Feud) into one plain script that JavaScriptCore can run:
//   node scripts/build-engine.mjs [outfile]      (default dist/engine.js)
// The parts that read files from the Pi (random boards from the clue and survey data) are swapped for stubs: the Apple
// TV engine never touches a disk, and none of that data belongs in the app.
import { build } from 'esbuild';
import { readFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.resolve(process.argv[2] ?? path.join(root, 'dist/engine.js'));
mkdirSync(path.dirname(out), { recursive: true });

const noFiles = {
  name: 'no-files',
  setup(b) {
    b.onLoad({ filter: /games[\\/](jeopardy[\\/]clues|feud[\\/]survey)\.js$/ }, () => ({
      contents: 'export const createRandomBoards = () => null; export const createRandomSurvey = () => null;',
      loader: 'js',
    }));
  },
};

const shim = readFileSync(path.join(root, 'engine/jsc/shim.js'), 'utf8');
await build({
  entryPoints: [path.join(root, 'engine/jsc/entry.js')],
  bundle: true, format: 'iife', target: 'es2020', platform: 'neutral', minify: false, legalComments: 'none',
  outfile: out, plugins: [noFiles], banner: { js: `// GENERATED by gamenight/scripts/build-engine.mjs: do not edit.\n${shim}` },
  logLevel: 'warning',
});
console.log(`Wrote ${out}`);
