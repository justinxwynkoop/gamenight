// Builds web/, the website on Vercel: a copy of public/ (phone, host, editor and TV pages), plus
//   config.js     points the pages at the Supabase relay (the publishable key is meant to be public)
//   tvhost.js     the game engine bundled for the browser, so the TV page can run the game itself (like the Apple TV app)
//   sets.json     the question sets that ship with the game
//   node scripts/build-web.mjs      (npm run build does this and the Apple TV app's copies in one go)
import { cpSync, rmSync, writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { build } from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'web');
const relay = JSON.parse(readFileSync(path.join(root, 'relay.config.json'), 'utf8'));

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const skip = new Set(['check.html']);   // the phone check page tests a home server's connection
cpSync(path.join(root, 'public'), out, {
  recursive: true,
  filter: (src) => !skip.has(path.basename(src)),
});
writeFileSync(path.join(out, 'config.js'), `globalThis.GN_RELAY = ${JSON.stringify(relay)};\n`);
writeFileSync(path.join(out, 'vercel.json'), JSON.stringify({
  cleanUrls: false,
  rewrites: [
    { source: '/', destination: '/play.html' },
    { source: '/play', destination: '/play.html' },
    { source: '/host', destination: '/host.html' },
    { source: '/editor', destination: '/editor.html' },
    { source: '/tv', destination: '/tv.html' },
  ],
  headers: [{ source: '/(.*)', headers: [{ key: 'Cache-Control', value: 'no-cache' }] }],
}, null, 2) + '\n');
// The engine for the TV page. Feud's random surveys read files on a home server, so they are left out (as in the app).
await build({
  entryPoints: [path.join(root, 'engine/browser/entry.js')],
  bundle: true, format: 'esm', target: 'es2020', platform: 'browser', minify: true, legalComments: 'none',
  outfile: path.join(out, 'tvhost.js'), logLevel: 'warning',
  banner: { js: '// GENERATED by scripts/build-web.mjs from engine/browser/entry.js: do not edit.' },
  plugins: [{
    name: 'no-files',
    setup(b) {
      b.onLoad({ filter: /games[\\/]feud[\\/]survey\.js$/ }, () => ({ contents: 'export const createRandomSurvey = () => null;', loader: 'js' }));
    },
  }],
});
execFileSync(process.execPath, [path.join(root, 'scripts/bundle-sets.mjs'), path.join(out, 'sets.json')], { stdio: 'ignore' });
console.log(`Wrote ${out}`);
